#!/usr/bin/env node
// Regenerate src/public-suffixes.ts from the Public Suffix List (PSL),
// the list of domain suffixes under which anyone can register a name
// (`com`, `co.uk`, ...). `.tld` in a userscript pattern means "any of
// these"; see docs/matching.md.
//
// Usage:
//   node scripts/update-public-suffixes.mjs              # fetch publicsuffix.org
//   node scripts/update-public-suffixes.mjs --file <dat> # use a local copy
//
// Only the ICANN section is kept: suffixes run by domain registries.
// The private section (`blogspot.com`, `github.io`, ...) is left out:
// a name under one of those belongs to whoever registered it there,
// so `www.google.tld` must not reach `www.google.blogspot.com`.
//
// The output is committed, so the build stays offline and the same
// every time. Rerun this now and then; the diff shows what changed.

import { writeFileSync, readFileSync } from 'node:fs';
import { domainToASCII } from 'node:url';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const SOURCE = 'https://publicsuffix.org/list/public_suffix_list.dat';
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'public-suffixes.ts');

const args = process.argv.slice(2);
if (args.includes('--help')) {
  console.log('Usage: node scripts/update-public-suffixes.mjs [--file <public_suffix_list.dat>]');
  process.exit(0);
}
const fileAt = args.indexOf('--file');
let text;
if (fileAt >= 0) {
  text = readFileSync(args[fileAt + 1], 'utf8');
} else {
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`Fetching ${SOURCE} failed: HTTP ${res.status}`);
  text = await res.text();
}

const begin = text.indexOf('// ===BEGIN ICANN DOMAINS===');
const end = text.indexOf('// ===END ICANN DOMAINS===');
if (begin < 0 || end < begin) throw new Error('The list has no ICANN section markers');

// Rules as the PSL writes them: `com`, `*.ck` (every label under ck),
// `!www.ck` (an exception to that wildcard). Hostnames reach us in
// their ASCII (punycode) form, so Unicode rules are converted.
const rules = [];
for (const raw of text.slice(begin, end).split('\n')) {
  const line = raw.trim();
  if (!line || line.startsWith('//')) continue;
  const prefix = line.startsWith('!') ? '!' : line.startsWith('*.') ? '*.' : '';
  const ascii = domainToASCII(line.slice(prefix.length));
  if (!ascii) throw new Error(`Rule ${line} has no ASCII form`);
  rules.push(prefix + ascii);
}
rules.sort();

const date = new Date().toISOString().slice(0, 10);
writeFileSync(OUT, `// Generated by scripts/update-public-suffixes.mjs; don't edit.
// The ICANN section of the Public Suffix List (${SOURCE}),
// fetched ${date}: ${rules.length} rules, one per line, in punycode.
// \`*.x\` covers every label under x; \`!y\` is an exception to one.
// Mozilla Public License 2.0 (https://mozilla.org/MPL/2.0/).
export const ICANN_SUFFIX_RULES = \`
${rules.join('\n')}
\`;
`);
console.log(`Wrote ${rules.length} rules to ${path.relative(process.cwd(), OUT)}`);
